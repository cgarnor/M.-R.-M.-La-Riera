export const DICTS: Record<Lang, Dict> = { es, en };

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = (DICTS[lang] ?? es)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Translated description of an error message produced by the engine, a worker or the main process. */
export function describeError(message: string | undefined, t: I18n['t']): string {
  const p = parseErrorCode(message);
  if (!p) return message || 'Error';
  const key = `err.${p.code}` as TKey;
  if (!(key in es)) return message || 'Error';
  const text = t(key, { d: p.detail ?? '' });
  // Remove an empty "()" left when the message has no detail.
  return text.replace(/\s*\(\s*\)/, '');
}

export interface I18n {
  lang: Lang;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
}

export const I18nContext = createContext<I18n>({ lang: 'es', t: (k, v) => translate('es', k, v) });
export const useI18n = () => useContext(I18nContext);
